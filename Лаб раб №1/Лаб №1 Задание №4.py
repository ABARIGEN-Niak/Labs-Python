num = int(input("Введите четырех-значенное число "))
num1 = num // 1000
num2 = num // 100 % 10
num3 = num // 10 % 10
num4 = num % 10
res1 = num1 + num2 + num3 + num4
res2 = num1 * num2 * num3 * num4
print('Сумма цифр числа ', num,' равна ', res1)
print('Произведение цифр числа ', num,' равна ', res2)

katet1 = int(input('Какой длинны 1й катет треугольника? '))
katet2 = int(input('Какой длинны 2й катет треугольника? '))
gipz = (katet1 ** 2 + katet2 ** 2)**0.5
plosh = katet1 * katet2 / 2
print('Гипотинуза этого треугольника равна ', gipz,' а площадь равна ', plosh)
